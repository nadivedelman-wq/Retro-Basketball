export type Glyph = { w: number; rows: string[] };

export const GLYPHS: Record<string, Glyph> = Object.fromEntries(
  Object.entries(G).map(([ch, rows]) => [ch, { w: rows[0].length, rows }]),
);

export function glyphFor(ch: string): Glyph {
  return GLYPHS[ch.toUpperCase()] ?? GLYPHS['?'];
}

/** Width in font pixels of a string (1px spacing between glyphs). */
export function textWidth(s: string): number {
  let w = 0;
  for (const ch of s) w += glyphFor(ch).w + 1;
  return Math.max(0, w - 1);
}

